export type Locale = "th" | "en";
const dictionaries: Record<Locale, Record<MessageKey, string>> = { en, th };
const STORAGE = "tableflow.locale";

type T = (key: MessageKey, vars?: Record<string, string | number>) => string;
type Ctx = { locale: Locale; t: T; setLocale: (l: Locale) => void; errorText: (e: ApiError) => string };

function format(template: string, vars?: Record<string, string | number>) {
  return vars ? template.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`)) : template;
}

function build(locale: Locale): Omit<Ctx, "setLocale"> {
  const dict = dictionaries[locale];
  const t: T = (key, vars) => format(dict[key] ?? en[key] ?? key, vars);
  // Known API error codes get a translated message; others show the server text.
  const errorText = (e: ApiError) => {
    const key = `error.${e.code}` as MessageKey;
    return key in dict ? dict[key] : e.message;
  };
  return { locale, t, errorText };
}

const I18n = createContext<Ctx>({ ...build("th"), setLocale: () => {} });

// Thai-first render (the pilot is a Thai restaurant); after mount the saved
// choice, else the browser language, applies. <html lang> follows.
export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("th");
  useEffect(() => {
    let saved: string | null = null;
    try {
      saved = localStorage.getItem(STORAGE);
    } catch {
      // storage unavailable
    }
    const next: Locale = saved === "th" || saved === "en" ? saved : navigator.language.toLowerCase().startsWith("th") ? "th" : "en";
    // eslint-disable-next-line react-hooks/set-state-in-effect
    setLocaleState(next);
  }, []);
  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);
  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    try {
      localStorage.setItem(STORAGE, l);
    } catch {
      // ignore
    }
  }, []);
  const value = useMemo(() => ({ ...build(locale), setLocale }), [locale, setLocale]);
  return <I18n.Provider value={value}>{children}</I18n.Provider>;
}

export const useI18n = () => useContext(I18n);
